function XScanrec = DecodeScans_custom( ...
    CodedY, CodedCb, CodedCr, tam, ...
    BITS_Y_DC, HUFFVAL_Y_DC, BITS_Y_AC, HUFFVAL_Y_AC, ...
    BITS_C_DC, HUFFVAL_C_DC, BITS_C_AC, HUFFVAL_C_AC)

    % Reconstruir la tabla de decodificacion DC de luminancia.
    [~, HUFFCODE] = HCodeTables(BITS_Y_DC, HUFFVAL_Y_DC);
    [mincode_Y_DC, maxcode_Y_DC, valptr_Y_DC] = ...
        HDecodingTables(BITS_Y_DC, HUFFCODE);

    % Reconstruir la tabla de decodificacion AC de luminancia.
    [~, HUFFCODE] = HCodeTables(BITS_Y_AC, HUFFVAL_Y_AC);
    [mincode_Y_AC, maxcode_Y_AC, valptr_Y_AC] = ...
        HDecodingTables(BITS_Y_AC, HUFFCODE);

    % Reconstruir la tabla de decodificacion DC de crominancia.
    [~, HUFFCODE] = HCodeTables(BITS_C_DC, HUFFVAL_C_DC);
    [mincode_C_DC, maxcode_C_DC, valptr_C_DC] = ...
        HDecodingTables(BITS_C_DC, HUFFCODE);

    % Reconstruir la tabla de decodificacion AC de crominancia.
    [~, HUFFCODE] = HCodeTables(BITS_C_AC, HUFFVAL_C_AC);
    [mincode_C_AC, maxcode_C_AC, valptr_C_AC] = ...
        HDecodingTables(BITS_C_AC, HUFFCODE);

    % Decodificar luminancia.
    YScanrec = DecodeSingleScan( ...
        CodedY, ...
        mincode_Y_DC, maxcode_Y_DC, valptr_Y_DC, HUFFVAL_Y_DC, ...
        mincode_Y_AC, maxcode_Y_AC, valptr_Y_AC, HUFFVAL_Y_AC, ...
        tam);

    % Decodificar crominancia Cb.
    CbScanrec = DecodeSingleScan( ...
        CodedCb, ...
        mincode_C_DC, maxcode_C_DC, valptr_C_DC, HUFFVAL_C_DC, ...
        mincode_C_AC, maxcode_C_AC, valptr_C_AC, HUFFVAL_C_AC, ...
        tam);

    % Decodificar crominancia Cr.
    CrScanrec = DecodeSingleScan( ...
        CodedCr, ...
        mincode_C_DC, maxcode_C_DC, valptr_C_DC, HUFFVAL_C_DC, ...
        mincode_C_AC, maxcode_C_AC, valptr_C_AC, HUFFVAL_C_AC, ...
        tam);

    % Reunir las tres componentes.
    XScanrec = cat(3, YScanrec, CbScanrec, CrScanrec);

    % PASO 15: mostrar la imagen original y la reconstruida.
    figure;

    subplot(1, 2, 1);
    imshow(X);
    title('Imagen original');

    subplot(1, 2, 2);
    imshow(Xrec);
    title('Imagen descomprimida custom');
end